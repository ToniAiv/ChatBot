def main():
    kb = json.load(open(KB, encoding="utf-8"))
    valid = [r for r in kb if r["title"] not in ("Ο ΛΟΓΑΡΙΑΣΜΟΣ ΜΟΥ", "")]
    table = MAPPINGS / "intent_to_service.csv"
    rows = list(csv.DictReader(table.open(encoding="utf-8-sig")))

    known = {r["intent"] for r in rows}
    unknown = [k for k in M if k not in known]
    if unknown:
        sys.exit(f"❌ intents που δεν υπάρχουν στον πίνακα: {unknown}")

    counts = {"auto": 0, "proposed": 0, "no_service": 0}
    for row in rows:
        if row["intent"] not in M:
            continue
        idx, conf, note = M[row["intent"]]
        if conf == "none":
            row.update(status="no_service", title="", url="",
                       note=f"δεν υπάρχει υπηρεσία — {note}" if note else "δεν υπάρχει αντίστοιχη υπηρεσία στο KB")
            counts["no_service"] += 1
        else:
            rec = valid[idx]
            row.update(status="auto" if conf == "high" else "proposed",
                       title=rec["title"], url=rec["url"],
                       note=(f"{conf}" + (f" — {note}" if note else "")))
            counts["auto" if conf == "high" else "proposed"] += 1

    order = {"proposed": 0, "no_service": 1, "review": 2, "auto": 3, "verified": 4}
    with table.open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(sorted(rows, key=lambda r: (order.get(r["status"], 9), r["intent"])))

    print(f"  auto (χρησιμοποιούνται)  : +{counts['auto']}")
    print(f"  proposed (θέλουν έλεγχο) : {counts['proposed']}")
    print(f"  no_service               : {counts['no_service']}")
    tot = {s: sum(1 for r in rows if r["status"] == s) for s in set(r["status"] for r in rows)}
    print(f"\n  σύνολο πίνακα: {tot}")


if __name__ == "__main__":
    main()
