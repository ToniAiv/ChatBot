def strip_acc(text: str) -> str:
    text = unicodedata.normalize("NFD", str(text))
    return "".join(c for c in text if unicodedata.category(c) != "Mn").lower()


def check_file(path: Path, seen_global: dict) -> tuple:
    rows = list(csv.DictReader(path.open(encoding="utf-8")))
    problems, warnings = [], []

    by_intent: dict = {}
    for i, r in enumerate(rows, start=2):
        by_intent.setdefault(r["intent"], []).append((i, r["text"]))

    for intent, items in by_intent.items():
        spec = SPEC.get(intent)
        if not spec:
            warnings.append(f"[{intent}] δεν υπάρχει ορισμός στο SPEC — παραλείπω")
            continue

        texts = [t for _, t in items]

        # 1. Άγκυρες
        for lineno, t in items:
            norm = strip_acc(t)
            if not any(a in norm for a in spec["anchors"]):
                problems.append((lineno, intent, "ΓΕΝΙΚΗ", t))

        # 2. Αναλογία (θέση στο αρχείο: 0-34 με λέξη, 35-69 χωρίς, 70-99 λαϊκές)
        if len(texts) != 100:
            warnings.append(f"[{intent}] {len(texts)} προτάσεις αντί για 100")
        else:
            hit = lambda t: any(k in strip_acc(t) for k in spec["keyword"])
            miss_a = [items[i][0] for i in range(35) if not hit(texts[i])]
            miss_b = [items[i][0] for i in range(35, 70) if hit(texts[i])]
            for ln in miss_a:
                problems.append((ln, intent, "ΛΕΙΠΕΙ Η ΛΕΞΗ", dict(items)[ln]))
            for ln in miss_b:
                problems.append((ln, intent, "ΠΕΡΙΣΣΕΥΕΙ Η ΛΕΞΗ", dict(items)[ln]))

        # 3. Διπλότυπα
        for t, c in Counter(texts).items():
            if c > 1:
                problems.append((0, intent, "ΔΙΠΛΟΤΥΠΟ", t))

    for _, t in [(i, r["text"]) for i, r in enumerate(rows)]:
        key = strip_acc(t).strip()
        if key in seen_global and seen_global[key] != path.name:
            problems.append((0, "-", "ΔΙΠΛΟΤΥΠΟ ΜΕΤΑΞΥ ΑΡΧΕΙΩΝ",
                             f"{t}  (και στο {seen_global[key]})"))
        seen_global[key] = path.name

    return rows, problems, warnings


def main() -> None:
    ap = argparse.ArgumentParser(description="Ποιοτικός έλεγχος dataset")
    ap.add_argument("--file", default=None)
    ap.add_argument("--dir", default=str(DATA_DIR))
    args = ap.parse_args()

    # Το ενοποιημένο αρχείο περιέχει αντίγραφα όλων των υπολοίπων, οπότε αν
    # μπει στον έλεγχο κάθε πρόταση φαίνεται διπλότυπη. Ελέγχουμε τις πηγές.
    files = ([Path(args.file)] if args.file
             else sorted(p for p in Path(args.dir).glob("*.csv")
                         if p.name != MERGED_NAME))
    if not files:
        sys.exit("Δεν βρέθηκαν αρχεία CSV")

    seen_global: dict = {}
    total_rows = total_problems = 0

    for path in files:
        rows, problems, warnings = check_file(path, seen_global)
        total_rows += len(rows)
        total_problems += len(problems)

        print("═" * 70)
        print(f"  {path.name}  —  {len(rows)} προτάσεις")
        print("═" * 70)
        for w in warnings:
            print(f"  ⚠  {w}")
        if not problems:
            print("  ✅ κανένα πρόβλημα")
        else:
            for lineno, intent, kind, text in sorted(problems):
                loc = f"γρ.{lineno}" if lineno else "—"
                print(f"  ❌ {loc:<8} [{kind}] {text[:62]}")
        print()

    print("─" * 70)
    print(f"  Σύνολο: {total_rows} προτάσεις, {total_problems} προβλήματα")
    sys.exit(1 if total_problems else 0)


if __name__ == "__main__":
    main()
