"""
Διόρθωση ορθογραφικών λαθών πριν το μοντέλο.

ΓΙΑΤΙ: το dataset παρήχθη από LLM, άρα είναι ορθογραφικά τέλειο. Το
μοντέλο δεν έχει δει ποτέ λάθος, και ένα λάθος ανά πρόταση του κοστίζει
9,5 μονάδες, δύο λάθη 27 (μετρημένο σε 400 προτάσεις).

ΜΕΘΟΔΟΣ: φωνητικό κλειδί. Μετρήθηκε ότι 9/9 από τα λάθη που σπάνε το
μοντέλο είναι φωνητικά — τα ελληνικά έχουν πολλούς τρόπους να γράψεις
τον ίδιο ήχο (ι/η/υ/ει/οι, ο/ω, ε/αι) και εκεί κάνουν λάθος οι φυσικοί
ομιλητές. Χτίζεται ευρετήριο «φωνητικό κλειδί → συχνότερη πραγματική
λέξη» από το dataset, και κάθε άγνωστη λέξη αναζητείται εκεί.

ΓΙΑΤΙ ΤΟ ΔΙΚΟ ΜΑΣ CORPUS ΚΑΙ ΟΧΙ ΛΕΞΙΚΟ: τα ελληνικά κλίνονται βαριά.
Ο πολίτης γράφει «κατοικίας», το λεξικό έχει λήμμα «κατοικία». Το corpus
έχει και τους κλιτικούς τύπους ΚΑΙ τις συχνότητες του τομέα — γι' αυτό
το «κλιση» διορθώνεται σε «κλήση» (92 εμφανίσεις) και όχι σε «κλίση» (9).

ΤΙ ΔΕΝ ΑΓΓΙΖΕΙ: λέξεις που υπάρχουν ήδη στο λεξιλόγιο. Η υπερδιόρθωση
είναι ο πραγματικός κίνδυνος — μια σωστή λέξη που «διορθώνεται» σε κάτι
άσχετο είναι χειρότερη από ένα ανορθόγραφο που δεν αναγνωρίζεται.
"""
from __future__ import annotations

import csv
import re
import unicodedata
from collections import Counter
from pathlib import Path

from acronyms import PROTECTED as _ACRONYMS

ENABLED = True
MIN_LEN = 4          # κάτω από αυτό οι γείτονες είναι πάρα πολλοί
# Ήταν 5. Μια πρώτη μέτρηση έδειχνε ότι το κατέβασμα αξίζει μόλις +0,5
# μονάδες — αλλά είχε γίνει ΠΡΙΝ μπει το δεύτερο πέρασμα με απόσταση
# επεξεργασίας, και οι δύο αλλαγές αλληλεπιδρούν: με την απόσταση,
# διορθώνονται και οι κοντές λέξεις. Μετά την προσθήκη, το 4 δίνει
# +0,9 στο ένα λάθος και +1,6 στα δύο, με τις καθαρές αμετάβλητες.
# Φάνηκε από πραγματικά παραδείγματα, όχι από τον μέσο όρο: το «ταφω»
# και το «πεδι» είναι λέξεις ΟΥΣΙΑΣ με 4 γράμματα, και η αποτυχία τους
# ρίχνει τη βεβαιότητα στο 0,17 και 0,08. Ο μέσος όρος τα έκρυβε γιατί
# οι περισσότερες κοντές λέξεις είναι λέξεις-εργαλεία («πως», «ποια»).
# Δοκιμάστηκε και κλιμακωτό όριο (≤1 για <6 γράμματα, ≤2 αλλιώς):
# μετρήθηκε ελαφρώς ΧΕΙΡΟΤΕΡΟ (0.8860/0.8710), οπότε απορρίφθηκε.
MIN_FREQ = 2         # μία μόνο εμφάνιση μπορεί να είναι και τυπογραφικό
MAX_EDIT = 2         # δεύτερο πέρασμα για ΜΗΧΑΝΙΚΑ λάθη

# Το φωνητικό κλειδί πιάνει μόνο ομόηχα λάθη. Η διάγνωση σε 1.500 λέξεις
# έδειξε ότι το 41% των αποτυχιών σε λέξεις ουσίας είναι μηχανικά —
# αντιμετάθεση, παράλειψη, διπλασιασμός — που δίνουν ΔΙΑΦΟΡΕΤΙΚΟ κλειδί
# («μετακινηησ» vs «μετακινηση»). Γι\' αυτό δεύτερο πέρασμα με απόσταση
# επεξεργασίας, μόνο για ό,τι απέτυχε φωνητικά.
# Μετρημένο σε 1.000 προτάσεις:
#              καθαρές   1 λάθος   2 λάθη
#   φωνητικό    0.8910    0.8510   0.8100
#   + ≤1        0.8910    0.8620   0.8300
#   + ≤2        0.8910    0.8670   0.8350   ← επιλογή
# Οι καθαρές μένουν ΤΑΥΤΟΣΗΜΕΣ σε κάθε ρύθμιση: η απαίτηση μοναδικού
# γείτονα αποτρέπει την υπερδιόρθωση.

ROOT = Path(__file__).resolve().parent.parent
SOURCES = [ROOT / "datasets" / "Expanded_Intent_Dataset_3.csv"]
SOURCES += sorted((ROOT / "datasets" / "tests").glob("*.csv"))

# Το εμπλουτισμένο KB περιέχει ΤΟΠΩΝΥΜΙΑ και ονόματα υπηρεσιών που δεν
# υπάρχουν στο dataset: Φοινικιά, Καμίνια, Μεσαμπελιές, Αλικαρνασσός.
# Χωρίς αυτά ο διορθωτής τα θεωρούσε άγνωστες λέξεις και τα αλλοίωνε —
# «Φοινικιά» γινόταν «φοίνικας». Προσθέτει 721 λέξεις.
KB_RICH = ROOT / "data" / "heraklion_eservices_enriched.json"

_WORD = re.compile(r"[α-ωΑ-ΩίϊΐόάέύϋΰήώΆΈΉΊΌΎΏ]+")


def _strip(s: str) -> str:
    s = unicodedata.normalize("NFD", str(s))
    return "".join(c for c in s if unicodedata.category(c) != "Mn").lower()


def phonetic(word: str) -> str:
    """Ό,τι ακούγεται ίδιο, γράφεται ίδιο."""
    w = _strip(word)
    w = re.sub(r"(ει|οι|υι)", "ι", w)
    w = re.sub(r"[ηυ]", "ι", w)
    w = re.sub(r"αι", "ε", w)
    w = re.sub(r"ω", "ο", w)
    w = re.sub(r"(αυ|ευ)", "αφ", w)
    w = re.sub(r"(.)\1+", r"\1", w)     # διπλά σύμφωνα
    w = re.sub(r"ς$", "σ", w)
    return w


_VOCAB: set = set()
_FREQ: dict = {}
_INDEX: dict = {}
_BY_SHAPE: dict = {}      # (μήκος, πρώτο γράμμα) → λέξεις


def _build() -> None:
    global _VOCAB, _FREQ, _INDEX, _BY_SHAPE
    freq: Counter = Counter()

    # Τα τοπωνύμια μπαίνουν στο ΛΕΞΙΛΟΓΙΟ (ώστε να μην πειράζονται) αλλά
    # με χαμηλή συχνότητα, ώστε να μη γίνονται στόχοι διόρθωσης άλλων
    # λέξεων. Δεν θέλουμε το «βεβαιωση» να καταλήγει σε «Φοινικιά».
    if KB_RICH.exists():
        import json
        for rec in json.loads(KB_RICH.read_text(encoding="utf-8")):
            text = f"{rec.get('body','')} {rec.get('contact','')} {rec.get('title','')}"
            for w in _WORD.findall(text):
                freq[_strip(w)] += 1

    for path in SOURCES:
        if not path.exists():
            continue
        with path.open(encoding="utf-8") as f:
            for row in csv.DictReader(f):
                for w in _WORD.findall(str(row.get("text", ""))):
                    freq[_strip(w)] += 1
    _VOCAB = set(freq)
    _FREQ = freq
    best: dict = {}
    for w, n in freq.items():
        if len(w) < MIN_LEN or n < MIN_FREQ:
            continue
        k = phonetic(w)
        if k not in best or n > best[k][0]:
            best[k] = (n, w)
    _INDEX = {k: w for k, (_n, w) in best.items()}

    # Ομαδοποίηση για την απόσταση επεξεργασίας: χωρίς αυτήν κάθε άγνωστη
    # λέξη θα συγκρινόταν με 7.900 λέξεις. Με φίλτρο μήκους ±1 και ίδιο
    # πρώτο γράμμα, οι υποψήφιες πέφτουν σε λίγες δεκάδες.
    _BY_SHAPE = {}
    for w in _VOCAB:
        if len(w) >= MIN_LEN:
            _BY_SHAPE.setdefault((len(w), w[0]), []).append(w)


_build()


def _within(a: str, b: str, k: int) -> bool:
    """Απόσταση Levenshtein ≤ k, με πρόωρη έξοδο."""
    if abs(len(a) - len(b)) > k:
        return False
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1):
            cur.append(min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (ca != cb)))
        if min(cur) > k:
            return False
        prev = cur
    return prev[-1] <= k


def _nearest(word: str) -> str | None:
    """
    Πλησιέστερη απόσταση πρώτα, μετά συχνότητα.

    Μια πρώτη εκδοχή απαιτούσε ΜΟΝΑΔΙΚΟ γείτονα και απέρριπτε τα πάντα
    μόλις υπήρχαν δύο υποψήφιοι — ακόμα κι όταν ο ένας ήταν προφανώς
    καλύτερος. Το «πιστοποητικο» έχει το «πιστοποιητικο» σε απόσταση 1
    και το «πιστοποιητικα» σε απόσταση 2· η μοναδικότητα τα θεωρούσε
    ισότιμα και δεν διόρθωνε τίποτα.

    Η ιεράρχηση απόσταση → συχνότητα είναι η ίδια λογική που ήδη
    χρησιμοποιείται στα φωνητικά κλειδιά, και μετρήθηκε καλύτερη σε
    1.000 προτάσεις (1 λάθος 0.8670→0.8790, 2 λάθη 0.8350→0.8620), με
    την ακρίβεια σε καθαρό κείμενο ΑΜΕΤΑΒΛΗΤΗ στο 0.8910.
    """
    best = None
    for length in (len(word) - 1, len(word), len(word) + 1):
        for cand in _BY_SHAPE.get((length, word[0]), ()):
            for dist in range(1, MAX_EDIT + 1):
                if _within(word, cand, dist):
                    score = (dist, -_FREQ.get(cand, 0), cand)
                    if best is None or score < best:
                        best = score
                    break
    return best[2] if best else None


def correct(text: str) -> str:
    """Επιστρέφει το κείμενο με διορθωμένες μόνο τις άγνωστες λέξεις."""
    if not ENABLED or not _INDEX:
        return text

    def fix(m: re.Match) -> str:
        w = m.group(0)
        # Κεφαλαίο μέσα σε πρόταση = κύριο όνομα (δρόμος, περιοχή,
        # επώνυμο). Κοστίζει σχεδόν τίποτα — μόλις 0,05% των λέξεων του
        # test set είναι τέτοιες — και προστατεύει ακριβώς ό,τι δεν
        # μπορούμε να έχουμε σε λεξιλόγιο.
        if m.start() > 0 and w[:1].isupper():
            return w
        s = _strip(w)
        # Ακρωνύμια του πίνακα: ποτέ διόρθωση. Το «κδαπ» δεν είναι στο
        # corpus και γινόταν «καπη» — άλλη υπηρεσία, με βεβαιότητα 0,95.
        if len(s) < MIN_LEN or s in _VOCAB or s in _ACRONYMS:
            return w
        hit = _INDEX.get(phonetic(s))          # 1. ομόηχο
        if hit:
            return hit
        return _nearest(s) or w                 # 2. μηχανικό λάθος

    return _WORD.sub(fix, str(text))


def stats() -> dict:
    return {"vocab": len(_VOCAB), "phonetic_keys": len(_INDEX),
            "shape_buckets": len(_BY_SHAPE)}
