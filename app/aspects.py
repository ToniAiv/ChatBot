"""
Ποια πτυχή μιας υπηρεσίας ρωτάει ο πολίτης.

Το BERT αναγνωρίζει ΠΟΙΑ υπηρεσία. Δεν ξέρει αν ο πολίτης θέλει την
υπηρεσία ή πληροφορίες ΓΙΑ αυτήν: «θέλω βεβαίωση κατοικίας» και «τι
χαρτιά θέλει η βεβαίωση κατοικίας» έχουν το ίδιο intent αλλά θέλουν
διαφορετική απάντηση.

Οι πτυχές είναι λίγες και αντιστοιχούν σε ενότητες που υπάρχουν στις
σελίδες του δήμου (δες scripts/extract_sections.py). Λύνονται με κανόνες
— δεν χρειάζεται μοντέλο για ένα κλειστό σύνολο πέντε κατηγοριών.

Η ΚΡΙΣΙΜΗ ΠΑΓΙΔΑ: «χρειάζομαι βεβαίωση κατοικίας» ΔΕΝ ρωτάει για
δικαιολογητικά — θέλει την υπηρεσία. Μόνο το «ΤΙ χρειάζομαι» ή το
«χρειάζομαι … χαρτιά/έγγραφα» είναι ερώτηση δικαιολογητικών. Ομοίως το
σκέτο «πού» («πού κάνω αίτηση») δεν ζητάει διεύθυνση.
"""
from __future__ import annotations

import re
import unicodedata


def _norm(s: str) -> str:
    s = unicodedata.normalize("NFD", str(s))
    return "".join(c for c in s if unicodedata.category(c) != "Mn").lower()


# Σειρά = προτεραιότητα όταν ταιριάζουν πολλές.
PATTERNS = [
    ("docs", [
        # «ποια» εξίσου συχνό με «τι». Η πρώτη εκδοχή είχε μόνο «τι» και
        # το «ποια έγγραφα χρειάζομαι» — ακριβώς η μετάφραση του «what
        # documents do I need» — περνούσε ως ερώτηση υπηρεσίας.
        r"\b(τι|ποια|ποιο) (χαρτια|χαρτι|εγγραφα|εγγραφο|δικαιολογητικα|πιστοποιητικα)\b.{0,20}(χρειαζ|θελ|πρεπει|απαιτ|φερ|ζητ)",
        r"\b(τι|ποια) (χαρτια|εγγραφα|δικαιολογητικα)\b",
        r"\bδικαιολογητικ",
        r"\bτι χρειαζ(ομαι|εται|ονται|ομαστε)",
        r"\bχρειαζ\w* .{0,25}(χαρτια|εγγραφα|δικαιολογητικα)",
        r"\bτι (πρεπει να |να )?(φερω|εχω μαζι|προσκομισω|καταθεσω|υποβαλω)",
        r"\b(απαραιτητα|απαιτουμενα) (εγγραφα|χαρτια)",
        r"\bτι απαιτειται",
        r"\bπρουποθεσ",
        r"\bτι (μου )?ζητα(νε|ει|ν)",
    ]),
    ("online", [
        r"\bηλεκτρονικα\b",
        r"\bonline\b",
        r"\bδιαδικτυακα\b",
        # «από το σπίτι» = ηλεκτρονικά, ΑΛΛΑ «έξω/μπροστά από το σπίτι» =
        # τοποθεσία. Βρέθηκε σε άγνωστες προτάσεις: «παρατημένο αμάξι έξω
        # από το σπίτι μου» ανιχνευόταν ως ερώτηση για ηλεκτρονική υποβολή.
        r"(?<!εξω )(?<!πισω )(?<!διπλα )(?<!κοντα )(?<!μπροστα )(?<!απεναντι )(?<!κατω )(?<!πανω )"
        r"\bαπο το (σπιτι|κινητο|υπολογιστη)",
        r"\bgov\.?gr\b",
        r"\bαυτοπροσωπως\b",
        r"\bμεσω (internet|ιντερνετ|διαδικτυου)",
        r"\bχωρις να (παω|πηγαινω|ερθω)",
    ]),
    ("contact", [
        r"\bτηλεφων",
        r"\be-?mail\b",
        r"\bεπικοινων",
        r"\b(σε )?ποια διευθυνση\b",
        r"\bπου βρισκεται\b",
        r"\bποιο (γραφειο|τμημα)\b",
        r"\bποιος ειναι (ο )?υπευθυνος",
        r"\bσε ποιον (να )?(απευθυνθω|μιλησω)",
    ]),
    ("cost", [
        r"\bποσο (κοστιζει|κανει|στοιχιζει|πληρωνω)",
        r"\bκοστος\b",
        r"\bπαραβολο\b",
    ]),
    ("time", [
        r"\bποσο (καιρο|χρονο|διαρκει)",
        r"\bσε ποσες (μερες|ημερες)",
        r"\bποτε (βγαινει|ετοιμαζεται|θα ειναι ετοιμο)",
    ]),
]

_COMPILED = [(a, [re.compile(p) for p in ps]) for a, ps in PATTERNS]


def detect_aspect(text: str) -> str | None:
    """'docs' | 'online' | 'contact' | 'cost' | 'time' | None."""
    t = _norm(text)
    for aspect, pats in _COMPILED:
        if any(p.search(t) for p in pats):
            return aspect
    return None
